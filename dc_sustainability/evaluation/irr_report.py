"""E07/R05 inter-rater reliability report: the numeric Markdown sections, from saved files.

Renders ``agreement.summary`` output (``agreement_report.json``) into the tables the
professor-requested report needs (#95): inputs and hashes, denominators, extraction
agreement, label agreement with marginals and confusion matrix, Cohen's kappa with any
undefined or label-imbalance explanation, completeness, and the draft-1 sections (raw
text, reference kind, rule §11.9 unfinished decisions) when the originals use them.

It never computes agreement itself and never edits an original. The interpretation
and limitations are written by the report owner after reading these numbers; the
notes generated here only state facts that follow mechanically from the counts.
"""

import hashlib
from pathlib import Path

LABELS = ("supported", "contradicted", "unsupported")
COMPLETENESS = ("decision", "reason", "evidence", "limitations")
ARTIFACTS = ("agreement_report.json", "matching.json", "adjudication.json")


def sha256_lf(path: Path) -> str:
    """SHA-256 over LF line endings, matching how the committed files are hashed."""
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def _pct(value: float | None) -> str:
    return "undefined" if value is None else f"{value:.1f}%"


def _kappa(value: float | None) -> str:
    return "undefined" if value is None else f"{value:.2f}"


def _share(value: float | None) -> str:
    return "undefined" if value is None else f"{value:.2f}"


def kappa_notes(block: dict, raters: tuple[str, str]) -> list[str]:
    """Mechanical explanations for an undefined kappa or a one-label rater."""
    n, marginals = block["n"], block.get("marginals")
    if n == 0:
        return ["Kappa is undefined: there are no matched pairs."]
    notes = []
    if block["kappa"] is None:
        notes.append(
            "Kappa is undefined: both raters gave every pair the same single label, so "
            "chance-expected agreement is 1."
        )
    elif marginals:
        for side, name in zip(("a", "b"), raters):
            used = [label for label in LABELS if marginals[side][label]]
            if len(used) == 1:
                notes.append(
                    f"Rater {side} ({name}) used only `{used[0]}` for all {n} pairs, so "
                    "chance-expected agreement equals observed agreement and kappa is 0 "
                    "whatever the other rater did. Read raw agreement with the confusion "
                    "matrix, not kappa, here."
                )
    return notes


def _label_section(title: str, block: dict, raters: tuple[str, str]) -> list[str]:
    lines = [
        f"**{title}:** {block['agreed']} of {block['n']} agreed, "
        f"**raw agreement {_pct(block['percent'])}**, "
        f"**Cohen's kappa {_kappa(block['kappa'])}**.",
        "",
    ]
    lines += [f"- {note}" for note in kappa_notes(block, raters)]
    if block.get("marginals"):
        lines += [
            "",
            "Label marginals:",
            "",
            f"| Label | Rater a ({raters[0]}) | Rater b ({raters[1]}) |",
            "|---|---|---|",
        ]
        lines += [
            f"| {x} | {block['marginals']['a'][x]} | {block['marginals']['b'][x]} |" for x in LABELS
        ]
        lines += [
            "",
            "Confusion matrix (rows: rater a; columns: rater b):",
            "",
            "| a \\ b | " + " | ".join(LABELS) + " |",
            "|---" * (len(LABELS) + 1) + "|",
        ]
        lines += [
            f"| {x} | " + " | ".join(str(block["confusion"][x][y]) for y in LABELS) + " |"
            for x in LABELS
        ]
    return lines + [""]


def _agreement_row(name: str, block: dict) -> str:
    return (
        f"| {name} | {block['agreed']}/{block['n']} | {_pct(block['percent'])} "
        f"| {_kappa(block['kappa'])} |"
    )


def render(
    report: dict,
    *,
    title: str,
    scope: str,
    originals: tuple[str, str],
    artifact_dir: Path | None = None,
) -> str:
    """The numeric report. ``originals`` are the two original files' display paths."""
    a, b = report["originals"]["a"], report["originals"]["b"]
    raters = (a["rater"], b["rater"])
    d, e = report["denominators"], report["extraction"]
    unmatched = d["unmatched_assertions"]
    lines = [
        f"# {title}",
        "",
        f"Scope: {scope}. Rubric `{report['rubric_version']}`. Generated by "
        "`scripts/render_irr_report.py` from the saved agreement report; every number "
        "below comes from the two unchanged originals, before adjudication.",
        "",
        "## Inputs (unchanged)",
        "",
        "| Rater | Original | SHA256 (LF) |",
        "|---|---|---|",
        f"| a: {a['rater']} | `{originals[0]}` | `{a['sha256']}` |",
        f"| b: {b['rater']} | `{originals[1]}` | `{b['sha256']}` |",
        "",
        "## Denominators",
        "",
        "| | Count |",
        "|---|---|",
        f"| Output units | {d['output_units']} |",
        f"| Empty-queue no-ops excluded | {d['not_applicable_outputs']} |",
        f"| Reviewed outputs | {d['reviewed_outputs']} |",
        f"| Missing ratings | {d['missing_ratings']} |",
        f"| Assertions, rater a / rater b | {d['assertions']['a']} / {d['assertions']['b']} |",
        f"| Matched assertions | {d['matched_assertions']} |",
    ]
    for side in ("a", "b"):
        parts = {k.split("_", 1)[1]: v for k, v in unmatched.items() if k.startswith(f"{side}_")}
        detail = ", ".join(f"{v} {k}" for k, v in sorted(parts.items()))
        lines.append(
            f"| Unmatched: rater {side}{f' ({detail})' if detail else ''} | {sum(parts.values())} |"
        )
    lines += [
        "",
        "## Results",
        "",
        f"**Extraction agreement (summary/limitation assertions):** {e['both']} matched, "
        f"{e['only_a']} only a, {e['only_b']} only b, "
        f"**agreement {_share(e['agreement'])}**.",
        "",
    ]
    lines += _label_section(
        "Label agreement, all matched assertions", report["labels_all_matched"], raters
    )
    if report["labels_claims_only"] != report["labels_all_matched"]:
        lines += _label_section(
            "Label agreement, claim records only", report["labels_claims_only"], raters
        )
    completeness = report["completeness"]
    lines += [
        f"**Completeness agreement ({d['reviewed_outputs']} reviewed outputs, supplementary):**",
        "",
        "| Part | Agreed | Raw | Kappa |",
        "|---|---|---|---|",
    ]
    lines += [_agreement_row(part, completeness[part]) for part in COMPLETENESS]
    lines.append("")
    if "raw_text" in report:
        raw = report["raw_text"]
        x = raw["extraction"]
        lines += [
            "### Raw-text assertions (rule §11.7, reported separately)",
            "",
            f"Extraction: {x['both']} matched, {x['only_a']} only a, {x['only_b']} only b, "
            f"agreement {_share(x['agreement'])}.",
            "",
        ]
        lines += _label_section("Raw-text label agreement", raw["labels"], raters)
    if "reference_kind" in report:
        k = report["reference_kind"]
        lines += [
            "### Reference kind (rule §11.6)",
            "",
            f"Both recorded a kind on {k['n']} matched assertions: {k['agreed']} agreed, "
            f"raw {_pct(k['percent'])}, kappa {_kappa(k['kappa'])}. "
            f"Recorded by one rater only: a {k['only_a']}, b {k['only_b']}.",
            "",
        ]
    if "cap_review" in report:
        c = report["cap_review"]
        lines += [
            "### Visibly unfinished text at the length limit (rule §11.9)",
            "",
            f"Computed cap hits: {c['cap_hits']}. Marked unfinished: a {c['unfinished']['a']}, "
            f"b {c['unfinished']['b']}.",
            "",
            "| Decision | Agreed | Raw | Kappa |",
            "|---|---|---|---|",
            _agreement_row("unfinished", c["agreement"]),
            "",
        ]
        lines += [f"- {note}" for note in kappa_notes(c["agreement"], raters)]
        lines.append("")
    lines += [
        "## Interpretation and limitations",
        "",
        "Written by the report owner from the numbers above; not generated.",
        "",
    ]
    if artifact_dir is not None:
        lines += ["## Artifacts", "", "| File | SHA256 (LF) |", "|---|---|"]
        lines += [
            f"| `{name}` | `{sha256_lf(artifact_dir / name)}` |"
            for name in ARTIFACTS
            if (artifact_dir / name).exists()
        ]
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"
